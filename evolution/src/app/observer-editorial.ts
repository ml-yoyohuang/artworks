/** Separate editorial rotation from event detection; never consumes the simulation RNG. */
export class ObserverEditorial {
  private positions = {knowledge:0,guide:0,reflection:0};
  next(kind: EditorialKind, state: ObservedState): string {
    if(kind==='knowledge') {
      for(let i=0;i<KNOWLEDGE.length;i++) {
        const item=KNOWLEDGE[this.positions.knowledge++ % KNOWLEDGE.length];
        if(item.type===undefined || state.types[item.type]>0) return item.text;
      }
    }
    const items=kind==='guide'?GUIDES:REFLECTIONS;
    return items[this.positions[kind]++ % items.length];
  }
}
